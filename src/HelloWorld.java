
//Подлючаем к программе Iterator — это интерфейс, который позволяет перебирать элементы коллекции по одному.
import java.util.Iterator;
//Дальше подключаем LinkedList - это структура данных,которая хранит элементы как цепочку
// (каждый элемент знает о следующем и предыдущем).
//У него есть специальный метод descendingIterator(),который идёт по элементам с конца.
import java.util.LinkedList;
//Подключает класс Scanner.
//System.in — это стандартный поток ввода (обычно клавиатура).
//Scanner подключается к этому потоку и читает данные.
import java.util.Scanner;

public class HelloWorld {
    public static void main(String[] args) {
        //Создаём объект Scanner в куче (heap).
        //Переменная scanner хранит ссылку на этот объект.
        //Объект связывается с потоком ввода System.in.
        Scanner scanner = new Scanner(System.in);
        //String input — объявляем переменную типа String с именем input. Она будет хранить всю введённую строку.
        //scanner.nextLine() — вызываем метод nextLine() у объекта scanner. Этот метод:
        //Ждёт, пока пользователь введёт текст и нажмёт Enter.
        //Читает всё до перевода строки.
        //Возвращает эту строку как результат
        System.out.println("Введите числа через пробел:");
        String input = scanner.nextLine();
        //scanner.close() — это ручное закрытие ресурса. AutoCloseable позволяет закрывать автоматически
        //через try-with-resources, но здесь мы просто вызываем close() явно.
        scanner.close();

        //РАЗБИЕНИЕ СТРОКИ
        //Метод split(" ") разбивает строку на части по разделителю (пробел).
        //Возвращает массив строк.
        //Метод проходит по строке слева направо.
        //Как только встречает пробел — отрезает часть и добавляет в массив.
        //Продолжает до конца строки.
        //input = "1 2 3 4 5"
        //numbers = ["1", "2", "3", "4", "5"]
        String[] numbers = input.split(" ");

        //СОЗДАНИЕ СПИСКА
        //LinkedList<Integer> — тип переменной.
        // LinkedList параметризован типом Integer.
        // Значит, список будет хранить только целые числа.
        //list — имя переменной.
        LinkedList<Integer> list = new LinkedList<Integer>();

        //ЦИКЛ ПО МАССИВУ
        for (int i = 0; i < numbers.length; i++) {
            //ПРЕОБРАЗОВАНИЕ СТРОКИ В ЧИСЛО
            //int value -создаём переменную для хранения целого числа
            //=	Присваивание-Кладём результат в переменную
            //Integer.parseInt()-Метод,который ревращает строку в число
            //numbers[i]- Берём строку из массива по индексу i
            //numbers[0] = "1" → value = 1
            //numbers[1] = "2" → value = 2
            int value = Integer.parseInt(numbers[i]);

            //ДОБАВЛЕНИЕ В СПИСОК
            //Здесь мы берём число, которое только что превратили из строки,
            //и добавляем его в конец нашего списка. Каждый раз, когда цикл проходит по новому числу,
            //оно добавляется в список, и так постепенно собираются все числа, которые ввел пользователь.
            list.add(value);
            System.out.println("До удаления: " + list);
        }


        //ЦИКЛ УДАЛЕНИЯ
        // int i = list.size() - 1 — начинаем с последнего индекса.
        //list.size() — количество элементов в списке (например, 10).
        //Минус 1 — потому что индексы начинаются с 0.
        //Если элементов 10, последний индекс — 9.
        //i >= 0 — идём до первого элемента включительно.
        // i-- — шаг назад (уменьшаем индекс).
        //Индексы: 0, 1, 2, 3, 4, 5
        //Идём с 5: удаляем? Нет (5 нечётный)
        //4: удаляем (чётный) → удаляем элемент "4" и т.д
        for (int j = list.size() - 1; j >= 0; j--) {
            //ПРОВЕРКА НА ЧЁТНОСТЬ
            //Вычисляет остаток от деления i на 2.
            // Если остаток 0 → число чётное.
            if (j % 2 == 0) {
                //УДАЛЕНИЕ ЭЛЕМЕНТА
                //list.remove(i) нужна, чтобы убрать из списка числа на чётных позициях.
                list.remove(j);
                System.out.println("После удаления: " + list);
            }
        }


        //СОЗДАНИЕ ОБРАТНОГО ИТЕРАТОРА
        //Здесь мы создаём специальный инструмент для обхода нашего списка в обратном порядке.
        //descendingIterator() — это встроенный метод LinkedList
        //который возвращает итератор, идущий с последнего элемента к первому.
        //Этот итератор начинает с конца списка, и каждый раз, когда мы вызываем next(),
        //он переходит к предыдущему элементу, а hasNext() проверяет, есть ли ещё элементы слева.
        Iterator<Integer> iterator = list.descendingIterator();
        //ЦИКЛ ПО ИТЕРАТОРУ
        //Проверяет, есть ли ещё элементы в итераторе.
        //Итератор хранит ссылку на текущий элемент.
        //При hasNext() проверяет, есть ли элемент слева от текущего
        while (iterator.hasNext()) {
            //ВЫВОД ЭЛЕМЕНТА
            //iterator.next() — получает следующий элемент от итератора
            //и переходит на один шаг вперёд (в обратном направлении).
            System.out.print(iterator.next());
            //ДОБАВЛЕНИЕ ПРОБЕЛА
            //Проверяет условие, есть ли ещё элементы после текущего.
            //Если есть — выводит пробел.
            //Без проверки:  2 4 6 8 10_ (лишний пробел в конце)
            if (iterator.hasNext()) {
                System.out.print(" ");
            }
        }
        //ПЕРЕВОД СТРОКИ
        //Выводит перевод строки (Enter).
        //Перемещает курсор на новую строку.
        System.out.println();
    }
}




