// КЛАСС Human
// Создаем класc Humen
class Humen {
            // ПОЛЯ (ПЕРЕМЕННЫЕ КЛАССА)
            // Приватное поле secret(оно должно быть доступно только внутри класса,поэтому private
            // String - тип данных (строка)
            private String secret;
            // Не приватное поле и оно доступно всему пакету в классе humen
            // (package-private) - поле доступно внутри пакета (без модификатора)
            // String - тип данных (строка)
            // gossip - имя переменной (сплетня)
            String gossip;
            // protected - это поле доступно внутри пакета + наследникам.(то.есть когда мы будем брать какой-нибудь
            //подкласс с полом(женщина или мужчина),эта функция experience будем передаваться по наследству от
            //общего класса Humen./Это поле не может быть приватным по логике,никто бы не смог прочитать общую сплетню
            // String - тип данных (строка)
            // experience - имя переменной (опыт)
            protected String experience;
            // public - поле доступно из любого места
            // String - тип данных (строка)
            // news - имя переменной (новости)
            // ; - конец инструкции
            public String news;

            // КОНСТРУКТОР
            //Метод для создания инициализации объетов,создает начальное значение при  создании,он важен
            //чтобы понять и создать начальные значения,без конструктора значения будут по умолчанию

            //Мы создаем констурктор с помощью public - конструктор доступен из любого места
            // Называем констурктор также как имя класса Hume(куда вносим все парметры для этого класса)
            // String secret - параметр: секрет
            // String gossip - параметр: сплетня
            // String experience - параметр: опыт
            // String news - параметр: новости
            public Humen(String secret, String gossip, String experience, String news) {
                // Дальше пишем метод this,который дает нам ссылку на поле secret и присваеваем
                // ему такой же параметр
                this.secret = secret;
                //также со всеми пораметрами мы так поступаем:
                this.gossip = gossip;
                this.experience = experience;
                this.news = news;
            }//закрываем косруктор

            // МЕТОД 1: getSecret() - private
            // Мы должны обратиться и получить приватное поле secret(пусто,потому что метод к которому мы
            // обращаем без параметров)
            // Геттер → get + с большой (getSecret())
            private String getSecret() {
                //Возварашем значение нашего приватного поля secret
                // Поле → с маленькой (secret)
                return secret;
            }

            // МЕТОД 2: getGossip() - package-private
            //Обращаемся ко второму нашему полю:
            String getGossip() {
                return gossip;
            }

            // МЕТОД 3: getExperience() - protected
            String getExperience() {
                return experience;
            }

            // МЕТОД 4: getNews() - public
            String getNews() {
                return news;
            }
        }//закрываем класс Humen(только сейчас потому что все вызовы и контсуркторы должны находиться в этом классе


//КЛЮЧЕВОЕ СЛОВО this
//this — это ссылка на ТЕКУЩИЙ объект.
// Зачем нужен:
// 1. Чтобы различить поле класса и параметр с одинаковым именем.
// Например: this.secret = secret;
       //↑ поле класса   ↑ параметр конструктора
//2. Чтобы передать текущий объект в другой метод.
//Чтобы вызвать другой конструктор (this(...))
// Без this Java не поймёт, что secret — это поле, а secret — это параметр.

//ГЕТТЕРЫ (GETTERS)
// Геттер — это метод, который возвращает значение поля.
//Зачем нужны:
//1. Чтобы ПОЛУЧИТЬ значение поля (не изменяя его).
//2. Чтобы дать доступ к private полям (безопасно).
//Чтобы скрыть внутреннюю реализацию (инкапсуляция).
// //Правила именования:
//Начинается с get + имя поля с большой буквы
//Например: getSecret(), getGossip(), getNews()
//Возвращает тот же тип, что и поле
