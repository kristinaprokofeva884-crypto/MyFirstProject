
public class HelloWorld {
    public static void main(String[] args) {
        // Day day - создаём переменную для текущего дня
        // : - "для каждого"
        // Day.values() - все дни недели
        // System.out.println - выводим строку
        // day - английское название (MONDAY)
        // " - " - разделитель
        // day.getRusName() - русское название (Понедельник)
        // " - Выходной? " - текст
        // day.isWeekend() - true/false (выходной или нет)
        for (Day day : Day.values()) {
        // Выводим информацию о текущем дне:
            // day - английское название (MONDAY)
            // day.getRusName() - русское название (Понедельник)
            // day.isWeekend() - true, если выходной, иначе false
            System.out.println(day + " - " + day.getRusName() + "-" + day.isWeekend());
        } // Закрывающая фигурная скобка метода main
    }
// Объявляем перечисление (Enum) Day - это специальный тип для списка фиксированных значений
// public - перечисление доступно из любого места
// enum - ключевое слово для объявления перечисления
// Day - имя перечисления
enum Day {
    // Перечисляем все дни недели - это константы (постоянные значения)
    // Каждое значение записывается заглавными буквами
    // Значения разделяются запятыми
    MONDAY,
    TUESDAY,
    WEDNESDAY,
    THURSDAY,
    FRIDAY,
    SATURDAY,
    SUNDAY;
    // Объявляем публичный метод isWeekend - он доступен из любого места
    // public - модификатор доступа, метод доступен всем
    // boolean - тип возвращаемого значения (true или false)
    // isWeekend - имя метода
    // () - пустой список параметров (метод ничего не принимает)
    public boolean isWeekend(){
        // Шаг 1: this == SATURDAY
        // Проверяем: текущий день (this) равен СУББОТЕ?

        // Шаг 2: this == SUNDAY
        // Проверяем: текущий день (this) равен ВОСКРЕСЕНЬЮ?

        // Шаг 3: || (логическое ИЛИ)
        // Если ХОТЯ БЫ ОДНО условие true → возвращаем true
        // Если оба условия false → возвращаем false

        // Шаг 4: return
        // Возвращаем результат (true или false)
        return this == SATURDAY || this == SUNDAY;
    }// Закрывающая фигурная скобка метода isWeekend

    // Объявляем публичный метод getRusName - он доступен из любого места
    // public - модификатор доступа, метод доступен всем
    // String - тип возвращаемого значения (строка)
    // getRusName - имя метода
    // () - пустой список параметров (метод ничего не принимает)
    public String getRusName(){
        // Используем конструкцию switch для проверки, какой именно день
        // switch - ключевое слово для множественного выбора
        // (this) - проверяем текущий день по ссылке:
        // { - открывающая скобка тела switch
        switch(this) {
            // Если текущий день - MONDAY (понедельник)
            // case - ключевое слово для указания значения
            // MONDAY - значение, которое проверяем
            // : - двоеточие после значения
            // return - возвращаем строку "Понедельник".return может возвращать сроки,
            // а result мы не возвращаем,потому что у нас нет сейчас такой перемнной в коде.
            // ; - конец инструкции
            case MONDAY:
                return "Понедельник";
            //и дальше мы перечисляемся через case все this ссылки на строки,которые у нас есть:
            case TUESDAY:
                return "Вторник";

            case WEDNESDAY:
                return "Среда";

            case THURSDAY:
                return "Четверг";

            case FRIDAY:
                return "Пятница";

            case SATURDAY:
                return "Суббота";

            case SUNDAY:
                return "Воскресенье";
            // Если вдруг случилось что-то неожиданное (это не должно произойти)
            // default - ключевое слово для случая, когда ничего не подошло
            // : - двоеточие после default
            // return - возвращаем строку "Неизвестно"
            // ; - конец инструкции
            default:
                return "Неизвестно";
        }   // Закрывающая фигурная скобка switch
    }// Закрывающая фигурная скобка метода getRusName
}// Закрывающая фигурная скобка Enum Day
    }//Закрвающая скобка класса HelloWorld.