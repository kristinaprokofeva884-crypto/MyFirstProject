
public class HelloWorld {
    public static void main(String[] args) {
        // Dog - тип переменной (класс Dog)
        // dog - имя переменной (ссылкa на объект)
        // = - оператор присваивания
        // new - ключевое слово для создания нового объекта
        // Dog() - конструктор класса Dog (создаёт объект)
        Dog dog = new Dog();
        // Cat - тип переменной (класс Cat)
        // cat - имя переменной (ссылка на объект)
        // = - оператор присваивания
        // new - ключевое слово для создания нового объекта
        // Cat() - конструктор класса Cat (создаёт объект)
        Cat cat = new Cat();
        // dog - переменная, в которой хранится объект Dog
        // . - оператор доступа (обращение к члену объекта)
        // catchCat - метод класса Dog (созданный нами)
        // (cat) - аргумент, переданный в метод (объект Cat)
        // ; - конец инструкции
        // Смысл: вызываем метод catchCat у объекта dog, передавая ему объект cat
        dog.catchCat(cat);
    }// } - закрывающая скобка метода main
}// } - закрывающая скобка класса Main
// КЛАСС CAT
// class - ключевое слово для создания класса
// Cat - имя класса
class Cat {
    // public - метод доступен из любого места
    // void - метод ничего не возвращает
    // sayHello - имя метода (говорит "Привет")
    // () - метод не принимает аргументов
    public void sayHello() {
        //Выводим на экран,что кошка издают голосом "Мяу!"
        System.out.println("Мяу!");
    }// } - закрывающая скобка метода sayHello
}// } - закрывающая скобка класса Cat
// КЛАСС DOG
// class - ключевое слово для создания класса
// Dog - имя класса
class Dog {
    // public - метод доступен из любого места
    // void - метод ничего не возвращает
    // sayHello - имя метода (говорит "Привет")
    // () - метод не принимает аргументов,также как и методо класса Кошки.
    public void sayHello() {
        //Выводим на экран,что собоака будет издавать звук "Ав!"
        System.out.println("Ав!");
    }// } - закрывающая скобка метода sayHello

    // public - метод доступен из любого места
    // void - метод ничего не возвращает
    // catchCat - имя метода (ловит кошку)
    // (Cat cat) - метод принимает один аргумент типа Cat
    // Cat - тип аргумента (класс Cat)
    // cat - имя аргумента (ссылка на переданную кошку)
    public void catchCat(Cat cat) {
        //Выводим для этого метода на экран,что кошка поймана(собакой)-по условиям
        System.out.println("Кошка поймана");
        // this - ссылка на текущий объект (эта же собака) -от класса собаки,который у нас есть уже в коде
        // . - оператор доступа
        // sayHello() - вызов метода sayHello у текущего объекта
        // ; - конец инструкции
        // Смысл: собака говорит "Ав!"
        this.sayHello();
        // cat - аргумент, переданный в метод (объект Cat)
        // . - оператор доступа
        // sayHello() - вызов метода sayHello у объекта cat
        // ; - конец инструкции
        // Смысл: кошка говорит "Мяу!"
        cat.sayHello();
    } // } - закрывающая скобка метода catchCat
}// } - закрывающая скобка класса Dog