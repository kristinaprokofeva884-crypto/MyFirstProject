// ЗАЧЕМ: Создаем наше собственное проверяемое исключение
// ПОЧЕМУ: class - ключевое слово для создания класса
// ПОЧЕМУ: MyNewException - имя нашего исключения
// ПОЧЕМУ: НЕТ public - это модификатор доступа по умолчанию (требование задачи)
// ПОЧЕМУ: extends Exception - наследуем от Exception (делаем проверяемым)
// ПОЧЕМУ: проверяемое исключение = компилятор заставляет нас его обрабатывать
class MyNewException extends Exception {

    // ЗАЧЕМ: Создаем конструктор с сообщением
    // ПОЧЕМУ: public - конструктор доступен из любого места
    // ПОЧЕМУ: MyNewException - имя конструктора (совпадает с именем класса)
    // ПОЧЕМУ: String message - параметр для текста ошибки
    // ПОЧЕМУ: super(message) - передаем сообщение родительскому классу Exception
    // ПОЧЕМУ: это позволяет выводить понятное сообщение при ошибке
    public MyNewException(String message) {
        super(message);  // Передаем сообщение в класс Exception
    }
}

// ============================================================
// ШАГ 2: СОЗДАЕМ КЛАСС С МЕТОДОМ testExp()
// ============================================================

// ЗАЧЕМ: Создаем класс для демонстрации работы исключения
// ПОЧЕМУ: class - ключевое слово для создания класса
// ПОЧЕМУ: TestClass - имя класса (может быть любым)
class TestClass {

    // ЗАЧЕМ: Создаем метод testExp(), который выбрасывает исключение
    // ПОЧЕМУ: public - метод доступен из любого места (требование задачи)
    // ПОЧЕМУ: void - метод ничего не возвращает
    // ПОЧЕМУ: testExp - имя метода
    // ПОЧЕМУ: throws MyNewException - объявляем, что метод может выбросить исключение
    // ПОЧЕМУ: это ОБЯЗАТЕЛЬНО для проверяемых исключений!
    public void testExp() throws MyNewException {

        // ЗАЧЕМ: Выбрасываем наше исключение
        // ПОЧЕМУ: throw - ключевое слово для выбрасывания исключения
        // ПОЧЕМУ: new MyNewException("Это проверяемое исключение!") - создаем объект исключения
        // ПОЧЕМУ: с сообщением, которое будет видно при ошибке
        // ПОЧЕМУ: метод testExp() сразу завершится при выбросе исключения
        throw new MyNewException("Это проверяемое исключение!");

        // ВАЖНО: код после throw НЕ ВЫПОЛНИТСЯ!
        // System.out.println("Это не будет напечатано");
    }
}

// ============================================================
// ШАГ 3: ПРОВЕРЯЕМ РАБОТУ В МЕТОДЕ main()
// ============================================================

public class HelloWorld {
    public static void main(String[] args) {

        // ЗАЧЕМ: Создаем объект класса TestClass
        // ПОЧЕМУ: чтобы вызвать метод testExp()
        TestClass test = new TestClass();

        // ЗАЧЕМ: Вызываем метод testExp() в блоке try-catch
        // ПОЧЕМУ: это ОБЯЗАТЕЛЬНО для проверяемых исключений!
        // ПОЧЕМУ: try - пробуем выполнить код, который может выбросить исключение
        // ПОЧЕМУ: catch - перехватываем исключение, если оно произошло
        try {
            // ЗАЧЕМ: Вызываем метод testExp()
            // ПОЧЕМУ: этот метод выбрасывает MyNewException
            // ПОЧЕМУ: если исключение выброшено, выполнение перейдет в catch
            test.testExp();

        } catch (MyNewException e) {
            // ЗАЧЕМ: Перехватываем наше исключение
            // ПОЧЕМУ: catch (MyNewException e) - ловим именно наше исключение
            // ПОЧЕМУ: e - переменная с объектом исключения
            // ПОЧЕМУ: e.getMessage() - получаем сообщение, которое передали в конструктор
            System.out.println("Перехвачено исключение: " + e.getMessage());
        }

        // ЗАЧЕМ: Код после try-catch выполнится в любом случае
        // ПОЧЕМУ: показывает, что программа продолжает работу после обработки ошибки
        System.out.println("Программа завершена успешно!");
    }
}
