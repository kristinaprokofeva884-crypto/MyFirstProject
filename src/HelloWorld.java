public class HelloWorld {
    public static void main(String[] args) {
        // СОЗДАЕМ ОБЪЕКТЫ КОМПЛЕКСНЫХ ЧИСЕЛ
        // Создаем первый объект ComplexNumber
        // ComplexNumber - тип переменной
        // num1- имя переменной (ссылка на объект)
        // = - оператор присваивания
        // new - создает новый объект в памяти
        // ComplexNumber(3.5, 2.0) - вызов конструктора с параметрами
        //   3.5 - (re)
        //   2.0 - часть (im)
        // Нам нужно создать объекты, чтобы проверить работу методов
        ComplexNumber num1 = new ComplexNumber(3.5, 2.0);

        // Создаем второй объект с ТАКИМИ ЖЕ значениями
        // Чтобы проверить, что equals() вернет true для одинаковых значений
        // Это отдельный объект в памяти, но с теми же числами(чтобы проверить ссылки)
        ComplexNumber num2 = new ComplexNumber(3.5, 2.0);

        // Создаем третий объект с ДРУГИМИ значениями (im = 2.1 вместо 2.0)
        // Чтобы проверить, что equals() вернет false для разных значений
        ComplexNumber num3 = new ComplexNumber(3.5, 2.1);

        // ПРОВЕРЯЕМ РАБОТУ equals() - сравнение ссылок объекта
        // Выводим результат сравнения num1 и num2 из созданных объектов
        // Проверяем, что метод equals() правильно сравнивает объекты
        // Ожидаем true, потому что значения одинаковые
        // Используем System.out.println() - для вывода на экран
        System.out.println("num1.equals(num2) = " + num1.equals(num2));

        // Теперь выводим результат сравнения num1 и num3
        // Ожидаем false, потому что im разные (2.0 vs 2.1)
        System.out.println("num1.equals(num3) = " + num1.equals(num3));

        // ТЕПЕРЬ ПРОВЕРЯЕМ hashCode()
        // Выводим хеш-код num1
        // Проверяем, что hashCode() возвращает какое-то число
        // Нужно знать, какой хеш у первого объекта
        System.out.println("num1.hashCode() = " + num1.hashCode());

        // Выводим хеш-код num2
        // Проверяем, что у равных объектов хеши совпадают
        // Ожидаем, что num2.hashCode() == num1.hashCode() - ожидаем, что они равны по hashCode
        System.out.println("num2.hashCode() = " + num2.hashCode());

        // А также выводим хеш-код num3
        // Проверяем, что у разных объектов хеши различаются
        // Ожидаем, что num3.hashCode() != num1.hashCode() - так как разные параметры.
        System.out.println("num3.hashCode() = " + num3.hashCode());

        // ПРОВЕРКА КОНТРАКТА equals() и hashCode()
        // Разделяем вывод для наглядности
        // \n - символ перевода строки, делает вывод читаемым
        System.out.println("\nОдинаковые объекты имеют одинаковый хеш");

        // Выводим для наглядности сравнения результата equals num1 и num2
        System.out.println("num1.equals(num2) = " + num1.equals(num2));

        // Теперь выводим для наглядности что эти хеш-коды равны с помощью hashCode
        // Это главное правило (контракт) - если equals() == true, то hashCode() должен быть одинаковым
        // Мы знаем, что (num1.hashCode() == num2.hashCode()) - сравниваем два числа и они точно true
        // Выводим результат сравнения
        System.out.println("num1.hashCode() == num2.hashCode()? " +
                (num1.hashCode() == num2.hashCode()));
    }
}

